test('actual Firestore Lite + current rules save workspace and independent named drafts, including archive/restore and conflict', async t => {
  const requireTests = createRequire(new URL('./firebase-emulator/package.json', import.meta.url));
  const { initializeTestEnvironment } = requireTests('@firebase/rules-unit-testing');
  const projectId = 'demo-tmc-fox5-draft-adapter';
  const environment = await initializeTestEnvironment({ projectId, firestore: { host: '127.0.0.1', port: 18080, rules: readFileSync(new URL('../firebase/firestore.rules', import.meta.url), 'utf8') } });
  await environment.clearFirestore();
  const app = initializeApp({ projectId }, projectId), db = lite.getFirestore(app);
  lite.connectFirestoreEmulator(db, '127.0.0.1', 18080, { mockUserToken: { sub: OWNER_UID, user_id: OWNER_UID } });
  const auth = { app, currentUser: { uid: OWNER_UID, getIdToken: async () => 'test-owner-session' } };
  const store = createFirebaseOwnerStore({ db, auth, ownerUid: OWNER_UID });
  t.after(async () => { store.dispose(); await lite.terminate(db); await deleteApp(app); await environment.clearFirestore(); await environment.cleanup(); });
  const initial = await store.load(); assert.equal(initial.revision, 0);
  const content = structuredClone(initial.draft); content.home.title = 'Saved workspace version';
  const workspace = await store.saveDraft(content, 0);
  assert.equal(workspace.revision, 1);
  assert.deepEqual((await store.load()).draft, content);
  assert.deepEqual(await store.listNamedDrafts(), [], 'Workspace Save as Draft is not a named-draft creation');
  const named = await store.saveNamedDraft('Independent named version', content);
  assert.equal((await store.listNamedDrafts()).length, 1);
  assert.deepEqual((await store.loadNamedDraft(named.id)).content, content);
  const rename = await store.renameNamedDraft(named.id, 'Renamed version', 1);
  assert.equal(rename.revision, 2);
  await assert.rejects(store.saveNamedDraft('Stale replacement', content, { id: named.id, expectedRevision: 1 }), { code: 'conflict' });
  await store.deleteNamedDraft(named.id, 2);
  assert.deepEqual(await store.listNamedDrafts(), []);
  assert.equal((await store.listTrashedNamedDrafts()).length, 1);
  const restored = await store.restoreNamedDraft(named.id, 'Restored version');
  assert.notEqual(restored.id, named.id);
  assert.deepEqual(restored.content, content);
  assert.equal((await store.listTrashedNamedDrafts()).length, 1);
  assert.deepEqual(await store.load(), workspace, 'Named actions never alter the working workspace');
  assert.equal((await lite.getDoc(lite.doc(db, 'site/published'))).exists(), false);
  await assert.rejects(lite.getDocs(lite.collection(db, 'ownerDrafts')), { code: 'permission-denied' }, 'Rules still require registry-based reads, not unrestricted collection queries');
});


test('explicit Save Draft atomically creates a visible restorable version and exact retry never duplicates it', async t => {
  const requireTests = createRequire(new URL('./firebase-emulator/package.json', import.meta.url));
  const { initializeTestEnvironment } = requireTests('@firebase/rules-unit-testing');
  const projectId = 'demo-tmc-fox5-draft-atomic';
  const environment = await initializeTestEnvironment({ projectId, firestore: { host: '127.0.0.1', port: 18080, rules: readFileSync(new URL('../firebase/firestore.rules', import.meta.url), 'utf8') } });
  await environment.clearFirestore();
  const app = initializeApp({ projectId }, projectId), db = lite.getFirestore(app);
  lite.connectFirestoreEmulator(db, '127.0.0.1', 18080, { mockUserToken: { sub: OWNER_UID, user_id: OWNER_UID } });
  const auth = { app, currentUser: { uid: OWNER_UID, getIdToken: async () => 'test-owner-session' } };
  let loseAcknowledgment = false;
  const storeModule = sourceLoader({ 'firebase/firestore/lite': { ...lite, async runTransaction(...args) { const result = await lite.runTransaction(...args); if (loseAcknowledgment) { loseAcknowledgment = false; throw Error('Simulated lost acknowledgment AFTER real emulator commit'); } return result; } } })('src/owner/firebase-store.ts');
  const store = storeModule.createFirebaseOwnerStore({ db, auth, ownerUid: OWNER_UID });
  t.after(async () => { store.dispose(); await lite.terminate(db); await deleteApp(app); await environment.clearFirestore(); await environment.cleanup(); });
  const initial = await store.load();
  // Payload is a JSON string inside Firestore: unusual insertion order and
  // omitted optional values must survive an exact lost-acknowledgment retry.
  const content = Object.fromEntries(Object.entries(initial.draft).reverse());
  content.design = { headingFontSize: 26, bodyFontSize: undefined };
  content.pages[0].titleAppearance = undefined;
  content.home.title = 'Visible in Drafts after Save as Draft';
  const persistedContent = JSON.parse(JSON.stringify(content));
  const version = { id: 'draft-explicit-stable-id', name: 'Draft exact timestamp version' };
  loseAcknowledgment = true;
  await assert.rejects(store.saveDraft(content, 0, version), { code: 'write' });
  const indexAfterCommit = (await lite.getDoc(lite.doc(db, 'ownerDraftIndex/current'))).data();
  assert.equal(indexAfterCommit.revision, 1);
  assert.equal((await store.load()).draft.home.title, content.home.title);
  assert.deepEqual((await store.listNamedDrafts()).map(item => item.id), [version.id]);
  const recovered = await store.saveDraft(content, 0, version);
  assert.equal(recovered.revision, 1);
  assert.deepEqual((await lite.getDoc(lite.doc(db, 'ownerDraftIndex/current'))).data(), indexAfterCommit, 'Exact replay is read-only');
  assert.deepEqual((await store.loadNamedDraft(version.id)).content, persistedContent, 'The visible entry loads the exact saved JSON snapshot');
  assert.equal(Object.hasOwn(content.design, 'bodyFontSize'), true, 'Input fields are not mutated by persistence');
  const changed = structuredClone(content); changed.home.title = 'Changed payload cannot reuse an operation';
  await assert.rejects(store.saveDraft(changed, 0, version), { code: 'conflict' });
  assert.deepEqual(await store.load(), recovered);
  const newerVersion = { id: 'draft-explicit-newer-id', name: 'A newer explicit version' };
  const newer = JSON.parse(JSON.stringify(await store.saveDraft(changed, 1, newerVersion)));
  assert.equal(newer.revision, 2);
  assert.equal((await store.listNamedDrafts()).length, 2);
  await assert.rejects(store.saveDraft(content, 0, version), error => error.code === 'conflict' && /already exists in Drafts/.test(error.message));
  assert.deepEqual(await store.load(), newer, 'Old uncertain operation never rewinds a newer workspace');
  assert.equal((await store.listNamedDrafts()).length, 2);
  await store.deleteNamedDraft(version.id, 1);
  const restored = await store.restoreNamedDraft(version.id, 'Restored exact named snapshot');
  assert.deepEqual(restored.content, persistedContent); assert.notEqual(restored.id, version.id);
  assert.deepEqual(await store.load(), newer, 'Loading/restoring the saved version does not replace the workspace or publish');
  for (let i = 0; i < 7; i++) await store.saveNamedDraft(`Existing saved slot ${i}`, content);
  assert.equal((await store.listNamedDrafts()).length, 9);
  const tenth = JSON.parse(JSON.stringify(await store.saveDraft(content, 2, { id: 'draft-tenth-slot', name: 'Last available explicit version' })));
  assert.equal(tenth.revision, 3);
  assert.deepEqual((await store.loadNamedDraft('draft-tenth-slot')).content, persistedContent);
  assert.equal((await store.listNamedDrafts()).length, 10);
  const beforeFull = (await lite.getDoc(lite.doc(db, 'ownerDraftIndex/current'))).data();
  await assert.rejects(store.saveDraft(content, 3, { id: 'draft-over-limit', name: 'Must not partially save' }), { code: 'limit' });
  assert.deepEqual(await store.load(), tenth);
  assert.deepEqual((await lite.getDoc(lite.doc(db, 'ownerDraftIndex/current'))).data(), beforeFull);
  assert.equal((await lite.getDoc(lite.doc(db, 'ownerDrafts/draft-over-limit'))).exists(), false);
  assert.equal((await lite.getDoc(lite.doc(db, 'site/published'))).exists(), false);
});

test('concurrent explicit versions use workspace CAS, and missing media cannot partially create either saved destination', async t => {
  const requireTests = createRequire(new URL('./firebase-emulator/package.json', import.meta.url));
  const { initializeTestEnvironment } = requireTests('@firebase/rules-unit-testing');
  const projectId = 'demo-tmc-fox5-draft-races';
  const environment = await initializeTestEnvironment({ projectId, firestore: { host: '127.0.0.1', port: 18080, rules: readFileSync(new URL('../firebase/firestore.rules', import.meta.url), 'utf8') } });
  await environment.clearFirestore();
  const app = initializeApp({ projectId }, projectId), db = lite.getFirestore(app);
  lite.connectFirestoreEmulator(db, '127.0.0.1', 18080, { mockUserToken: { sub: OWNER_UID, user_id: OWNER_UID } });
  const auth = { app, currentUser: { uid: OWNER_UID, getIdToken: async () => 'test-owner-session' } };
  const store = createFirebaseOwnerStore({ db, auth, ownerUid: OWNER_UID });
  t.after(async () => { store.dispose(); await lite.terminate(db); await deleteApp(app); await environment.clearFirestore(); await environment.cleanup(); });
  const initial = await store.load();
  const missing = structuredClone(initial.draft); missing.home.image.src = '/api/cloud-media/11111111-1111-4111-8111-111111111111';
  await assert.rejects(store.saveDraft(missing, 0, { id: 'draft-missing-asset', name: 'Invalid missing asset' }), { code: 'write' });
  assert.equal((await lite.getDoc(lite.doc(db, 'ownerWorkspace/current'))).exists(), false);
  assert.equal((await lite.getDoc(lite.doc(db, 'ownerDraftIndex/current'))).exists(), false);
  assert.equal((await lite.getDoc(lite.doc(db, 'ownerDrafts/draft-missing-asset'))).exists(), false);
  const left = structuredClone(initial.draft), right = structuredClone(initial.draft);
  left.home.title = 'Concurrent left'; right.home.title = 'Concurrent right';
  const results = await Promise.allSettled([
    store.saveDraft(left, 0, { id: 'draft-race-left', name: 'Concurrent left' }),
    store.saveDraft(right, 0, { id: 'draft-race-right', name: 'Concurrent right' }),
  ]);
  assert.equal(results.filter(result => result.status === 'fulfilled').length, 1);
  assert.equal(results.find(result => result.status === 'rejected').reason.code, 'conflict');
  const workspace = await store.load(), named = await store.listNamedDrafts();
  assert.equal(workspace.revision, 1); assert.equal(named.length, 1);
  assert.deepEqual((await store.loadNamedDraft(named[0].id)).content, workspace.draft);
  const losingId = named[0].id === 'draft-race-left' ? 'draft-race-right' : 'draft-race-left';
  assert.equal((await lite.getDoc(lite.doc(db, 'ownerDrafts', losingId))).exists(), false);
  const before = (await lite.getDoc(lite.doc(db, 'ownerDraftIndex/current'))).data();
  auth.currentUser = null;
  await assert.rejects(store.saveDraft(left, 1, { id: 'draft-ended-session', name: 'Not allowed' }), { code: 'unavailable' });
  assert.deepEqual((await lite.getDoc(lite.doc(db, 'ownerDraftIndex/current'))).data(), before);
  assert.equal((await lite.getDoc(lite.doc(db, 'site/published'))).exists(), false);
});

test('0331 named rename lost acknowledgement reconciles by fresh read; stale CAS cannot overwrite newer name', async t => {
  const requireTests = createRequire(new URL('./firebase-emulator/package.json', import.meta.url));
  const { initializeTestEnvironment } = requireTests('@firebase/rules-unit-testing');
  const projectId = 'demo-tmc-0331-rename-unknown';
  const environment = await initializeTestEnvironment({ projectId, firestore: { host: '127.0.0.1', port: 18080, rules: readFileSync(new URL('../firebase/firestore.rules', import.meta.url), 'utf8') } });
  await environment.clearFirestore();
  const app = initializeApp({ projectId }, projectId), db = lite.getFirestore(app);
  lite.connectFirestoreEmulator(db, '127.0.0.1', 18080, { mockUserToken: { sub: OWNER_UID, user_id: OWNER_UID } });
  const auth = { app, currentUser: { uid: OWNER_UID, getIdToken: async () => 'test-owner-session' } };
  let loseAcknowledgment = false;
  const storeModule = sourceLoader({ 'firebase/firestore/lite': { ...lite, async runTransaction(...args) { const result = await lite.runTransaction(...args); if (loseAcknowledgment) { loseAcknowledgment = false; throw Error('Synthetic acknowledgement lost AFTER actual rename commit'); } return result; } } })('src/owner/firebase-store.ts');
  const store = storeModule.createFirebaseOwnerStore({ db, auth, ownerUid: OWNER_UID });
  t.after(async () => { store.dispose(); await lite.terminate(db); await deleteApp(app); await environment.clearFirestore(); await environment.cleanup(); });
  const initial = await store.load(), saved = await store.saveNamedDraft('Before rename', initial.draft);
  loseAcknowledgment = true;
  await assert.rejects(store.renameNamedDraft(saved.id, 'Confirmed after reread', saved.revision), { code: 'write' });
  const recovered = await store.loadNamedDraft(saved.id);
  assert.equal(recovered.name, 'Confirmed after reread'); assert.equal(recovered.revision, saved.revision + 1);
  assert.deepEqual(recovered.content, initial.draft);
  await assert.rejects(store.renameNamedDraft(saved.id, 'Unsafe old retry', saved.revision), { code: 'conflict' });
  assert.equal((await store.loadNamedDraft(saved.id)).name, recovered.name);
  assert.equal((await store.listNamedDrafts()).length, 1);
  assert.deepEqual(await store.load(), initial);
  assert.equal((await lite.getDoc(lite.doc(db, 'site/published'))).exists(), false);
});
